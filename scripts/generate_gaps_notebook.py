    "import pretty_midi\n",
    "import xml.etree.ElementTree as ET\n",
    "from typing import List, Dict, Any\n",
    "\n",
    "# Standard Guitar Open String MIDI pitches\n",
    "OPEN_MIDIS = {\n",
    "    6: 40,  # E2\n",
    "    5: 45,  # A2\n",
    "    4: 50,  # D3\n",
    "    3: 55,  # G3\n",
    "    2: 59,  # B3\n",
    "    1: 64   # E4\n",
    "}\n",
    "\n",
    "def parse_musicxml_tablature(xml_path: str) -> Dict[str, Any]:\n",
    "    \"\"\"Extract explicit string and fret notations from MusicXML if available.\"\"\"\n",
    "    if not xml_path or not os.path.exists(xml_path):\n",
    "        return {}\n",
    "    \n",
    "    tree = ET.parse(xml_path)\n",
    "    root = tree.getroot()\n",
    "    tab_annotations = []\n",
    "    \n",
    "    for note in root.iter(\"note\"):\n",
    "        step = note.find(\".//pitch/step\")\n",
    "        octave = note.find(\".//pitch/octave\")\n",
    "        tech = note.find(\".//notations/technical\")\n",
    "        string_elem = tech.find(\"string\") if tech is not None else None\n",
    "        fret_elem = tech.find(\"fret\") if tech is not None else None\n",
    "        \n",
    "        if string_elem is not None and fret_elem is not None:\n",
    "            tab_annotations.append({\n",
    "                \"string\": int(string_elem.text),\n",
    "                \"fret\": int(fret_elem.text)\n",
    "            })\n",
    "    return tab_annotations\n",
    "\n",
    "def load_gaps_ground_truth(midi_path: str, xml_path: str = None) -> List[Dict[str, Any]]:\n",
    "    \"\"\"\n",
    "    Load time-aligned ground-truth note events from GAPS aligned MIDI.\n",
    "    Extracts onset, offset, duration, pitch, string, and fret.\n",
    "    \"\"\"\n",
    "    pm = pretty_midi.PrettyMIDI(midi_path)\n",
    "    gt_notes = []\n",
    "    \n",
    "    for instrument in pm.instruments:\n",
    "        for n in instrument.notes:\n",
    "            pitch = int(n.pitch)\n",
    "            onset = float(n.start)\n",
    "            offset = float(n.end)\n",
    "            \n",
    "            # Derive optimal/most canonical string & fret under ergonomic guitar reach\n",
    "            candidate_strings = []\n",
    "            for s in [6, 5, 4, 3, 2, 1]:\n",
    "                fret = pitch - OPEN_MIDIS[s]\n",
    "                if 0 <= fret <= 19:\n",
    "                    candidate_strings.append((s, fret))\n",
    "            \n",
    "            if candidate_strings:\n",
    "                # Default canonical assignment (prefer lower frets / open positions if not specified)\n",
    "                best_s, best_f = min(candidate_strings, key=lambda x: x[1])\n",
    "            else:\n",
    "                best_s, best_f = (6, max(0, pitch - 40))\n",
    "                \n",
    "            gt_notes.append({\n",
    "                \"onset\": onset,\n",
    "                \"offset\": offset,\n",
    "                \"duration\": offset - onset,\n",
    "                \"pitch\": pitch,\n",
    "                \"string\": best_s,\n",
    "                \"fret\": best_f\n",
    "            })\n",
    "            \n",
    "    gt_notes.sort(key=lambda x: (x[\"onset\"], x[\"string\"]))\n",
    "    return gt_notes\n",
    "\n",
    "print(\"Ground truth parser defined successfully.\")"
