    "    import pretty_midi\n",
    "\n",
    "from typing import List, Dict, Any\n",
    "from guitarset_evaluator import OPEN_MIDIS\n",
    "\n",
    "def load_gaps_ground_truth(midi_path: str) -> List[Dict[str, Any]]:\n",
    "    \"\"\"\n",
    "    Extract ground truth notes (onset, offset, duration, pitch, string, fret) from aligned MIDI.\n",
    "    \"\"\"\n",
    "    pm = pretty_midi.PrettyMIDI(midi_path)\n",
    "    gt_notes = []\n",
    "    \n",
    "    for instrument in pm.instruments:\n",
    "        for n in instrument.notes:\n",
    "            pitch = int(n.pitch)\n",
    "            onset = float(n.start)\n",
    "            offset = float(n.end)\n",
    "            \n",
    "            # Find valid guitar string and fret\n",
    "            cands = []\n",
    "            for s in [1, 2, 3, 4, 5, 6]:\n",
    "                f = pitch - OPEN_MIDIS[s]\n",
    "                if 0 <= f <= 19:\n",
    "                    cands.append((s, f))\n",
    "            if cands:\n",
    "                best_s, best_f = min(cands, key=lambda x: x[1])\n",
    "            else:\n",
    "                best_s, best_f = (6, max(0, pitch - 40))\n",
    "                \n",
    "            gt_notes.append({\n",
    "                \"onset\": onset,\n",
    "                \"offset\": offset,\n",
    "                \"duration\": offset - onset,\n",
    "                \"pitch\": pitch,\n",
    "                \"string\": best_s,\n",
    "                \"fret\": best_f\n",
    "            })\n",
    "            \n",
    "    gt_notes.sort(key=lambda x: (x[\"onset\"], x[\"string\"]))\n",
    "    return gt_notes\n",
    "\n",
    "print(\"✅ Ground truth loader ready.\")"
